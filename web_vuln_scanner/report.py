"""Report writers: JSON and self-contained HTML."""

from __future__ import annotations

import html as html_lib
import json
from pathlib import Path

from .scanner import ScanResult

_SEVERITY_CLASS = {"High": "high", "Medium": "medium", "Low": "low", "Info": "info"}


def write_json_report(result: ScanResult, path: str | Path) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(json.dumps(result.to_dict(), indent=2), encoding="utf-8")
    return path


def write_html_report(result: ScanResult, path: str | Path) -> Path:
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    data = result.to_dict()
    summary = data["summary"]

    rows = []
    for f in data["findings"]:
        status = "VULNERABLE" if f["vulnerable"] else "OK"
        cls = _SEVERITY_CLASS.get(f["severity"], "info")
        rows.append(
            "<tr>"
            f"<td>{html_lib.escape(f['id'])}</td>"
            f"<td>{html_lib.escape(f['name'])}</td>"
            f"<td class='{cls}'>{html_lib.escape(f['severity'])}</td>"
            f"<td class='{cls}'>{status}</td>"
            f"<td>{html_lib.escape(f['url'])}</td>"
            f"<td>{html_lib.escape(f['evidence'])}</td>"
            f"<td>{html_lib.escape(f['detail'])}</td>"
            f"<td>{html_lib.escape(f['remediation'])}</td>"
            "</tr>"
        )
    rows_html = "\n".join(rows) if rows else "<tr><td colspan='8'>No findings.</td></tr>"

    doc = f"""<!DOCTYPE html>
<html lang="en">
<head>
<meta charset="utf-8">
<title>web-vuln-scanner report — {html_lib.escape(data['target'])}</title>
<style>
body {{ font-family: system-ui, sans-serif; margin: 2rem; color: #1a1a1a; }}
h1 {{ font-size: 1.4rem; }} table {{ border-collapse: collapse; width: 100%; font-size: 0.85rem; }}
th, td {{ border: 1px solid #ccc; padding: 6px 8px; text-align: left; vertical-align: top; }}
th {{ background: #222; color: #fff; }}
.high {{ color: #b00020; font-weight: bold; }} .medium {{ color: #b26a00; font-weight: bold; }}
.low {{ color: #555; }} .info {{ color: #555; }}
.summary {{ background: #f4f4f4; padding: 1rem; margin-bottom: 1rem; }}
footer {{ margin-top: 2rem; color: #666; font-size: 0.8rem; }}
</style>
</head>
<body>
<h1>web-vuln-scanner report</h1>
<div class="summary">
<p><strong>Target:</strong> {html_lib.escape(data['target'])}</p>
<p><strong>Scanned:</strong> {html_lib.escape(data['scanned_at'])} (UTC) &mdash; {data['duration_seconds']}s</p>
<p><strong>Pages crawled:</strong> {len(data['pages_crawled'])}</p>
<p><strong>Findings:</strong> {summary['total']} total &mdash; {summary['vulnerable']} vulnerable
({summary['high']} High, {summary['medium']} Medium, {summary['low']} Low, {summary['info']} Info)</p>
<p><strong>Note:</strong> Safe, non-destructive probes only. Scan only targets you are authorised to test.</p>
</div>
<table>
<thead><tr><th>ID</th><th>Check</th><th>Severity</th><th>Status</th><th>URL</th><th>Evidence</th><th>Detail</th><th>Remediation</th></tr></thead>
<tbody>
{rows_html}
</tbody>
</table>
<footer>Generated by web-vuln-scanner v0.1.0 (Tytechlabs, GPL-3.0).</footer>
</body>
</html>
"""
    path.write_text(doc, encoding="utf-8")
    return path
